"""Run the Feed Doctor pipeline: python run.py  (needs: pip install duckdb)"""
import duckdb, pathlib
ROOT = pathlib.Path(__file__).parent
TRANS = {**{str(d): d for d in range(10)}, **dict(zip("ABCDEFGH", range(1, 9))), **dict(zip("JKLMN", range(1, 6))),
         "P": 7, "R": 9, **dict(zip("STUVWXYZ", range(2, 10)))}
W = [8, 7, 6, 5, 4, 3, 2, 10, 0, 9, 8, 7, 6, 5, 4, 3, 2]

def vin_check_ok(vin: str) -> bool:
    """North American VIN check digit (position 9)."""
    if vin is None or len(vin) != 17 or any(c not in TRANS for c in vin.upper()):
        return False
    r = sum(TRANS[c] * w for c, w in zip(vin.upper(), W)) % 11
    return vin[8].upper() == ("X" if r == 10 else str(r))

con = duckdb.connect(str(ROOT / "out/feed_doctor.duckdb"))
con.create_function("vin_check_ok", vin_check_ok, ["VARCHAR"], "BOOLEAN")
import os; os.chdir(ROOT)
for f in sorted((ROOT / "sql").glob("*.sql")):
    con.execute(f.read_text())
    print("ran", f.name)
con.close()

# ---------- export the scorecard ----------
import json
con = duckdb.connect(str(ROOT / "out/feed_doctor.duckdb"), read_only=True)
def rows(sql): 
    r = con.execute(sql); cols = [d[0] for d in r.description]
    return [dict(zip(cols, x)) for x in r.fetchall()]
bad_holdout = con.execute("""
  WITH v AS (SELECT * FROM read_csv('data/eval/ground_truth_holdout_vehicles.csv', header = true)),
       st AS (SELECT listing_id FROM read_csv('data/eval/ground_truth_holdout.csv', header = true) WHERE issue_type = 'stale_us_date_format')
  SELECT count(DISTINCT i.listing_id) FROM inventory_clean i JOIN v USING (listing_id)
  WHERE i.feed = 'D' AND (i.price <> v.price OR abs(i.miles - v.miles) > 100 OR i.year <> v.year
                          OR i.listing_id IN (SELECT listing_id FROM st))""").fetchone()[0]
sc = {
  "feeds": rows("SELECT * FROM score_feeds"),
  "agent_ready": rows("SELECT * FROM score_ready"),
  "fields": rows("SELECT * FROM score_fields ORDER BY before_pct, field"),
  "queries": rows("SELECT * FROM score_queries"),
  "detection_planted": rows("SELECT * FROM eval_detection ORDER BY planted DESC"),
  "detection_holdout": rows("SELECT * FROM eval_holdout ORDER BY planted DESC"),
  "holdout_bad_listings_published": bad_holdout,
  "holdout_listings_published": con.execute("SELECT count(*) FROM inventory_clean WHERE feed = 'D'").fetchone()[0],
}
(ROOT / "out/scorecard.json").write_text(json.dumps(sc, indent=1, default=str))

def md_table(rs):
    if not rs: return ""
    cols = list(rs[0].keys())
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join("" if v is None else str(v) for v in r.values()) + " |" for r in rs]
    return "\n".join(out)
ready = {r["stage"]: r for r in sc["agent_ready"]}
pl = sc["detection_planted"]; ho = sc["detection_holdout"]
md = f"""# Feed Doctor scorecard

Generated by `python run.py`. Synthetic feeds; specs are illustrative.

## Agent-ready listings
Before: {ready['before']['agent_ready']} of {ready['before']['listings']} listings as received.
After: {ready['after']['agent_ready']} of {ready['after']['listings']} shoppable listings.

## Feeds
{md_table(sc['feeds'])}

## Field coverage (% of listings where a search filter could use the field)
{md_table(sc['fields'])}

## Can the 20 v0.1 audit queries be answered from this data?
{md_table(sc['queries'])}

## Detection of planted issues (feeds A–C)
Caught {sum(r['caught'] for r in pl)} of {sum(r['planted'] for r in pl)}; {sum(r['flagged'] for r in pl) - sum(r['caught'] for r in pl)} false flags.

{md_table(pl)}

## Hold-out dealer (feed D): problem variants written after the rules
Handled {sum(r['handled'] for r in ho)} of {sum(r['planted'] for r in ho)}. {sc['holdout_bad_listings_published']} of {sc['holdout_listings_published']} hold-out listings reached the clean inventory with a wrong value.

{md_table(ho)}
"""
(ROOT / "out/scorecard.md").write_text(md)
print("wrote out/scorecard.md and out/scorecard.json")
